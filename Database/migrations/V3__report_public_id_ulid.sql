-- V3 immutable migration. Apply ONCE after V2 and an approved backup.
-- PostgreSQL 17+. Standalone SQL: usable by psql or DBeaver Execute SQL Script.
-- Stop on first error. Adds public_id (rpt_ + 26-char Crockford Base32 ULID) to reports.
-- Internal BIGINT PK reports.id and all foreign keys remain unchanged.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '120s';
SET LOCAL search_path = public, pg_catalog;

-- Pause application writers on reports
LOCK TABLE public.reports IN SHARE ROW EXCLUSIVE MODE;

DO $preflight_v3$
BEGIN
    IF current_setting('server_version_num')::integer < 170000 THEN
        RAISE EXCEPTION 'V3 is validated for PostgreSQL 17+; inspect compatibility before upgrading';
    END IF;

    -- Ensure V2 baseline is present
    IF to_regclass('public.report_metrics') IS NULL OR to_regclass('public.refresh_tokens') IS NULL THEN
        RAISE EXCEPTION 'V2 baseline not found; apply V2 migration before V3';
    END IF;

    IF to_regclass('public.reports') IS NULL THEN
        RAISE EXCEPTION 'Missing reports table';
    END IF;

    -- If public_id already exists, abort to prevent rerun / schema drift
    IF EXISTS (
        SELECT 1 FROM pg_attribute
        WHERE attrelid = 'public.reports'::regclass
          AND attname = 'public_id'
          AND NOT attisdropped
    ) THEN
        RAISE EXCEPTION 'Column reports.public_id already exists: V3 already applied or schema drift; do not rerun blindly';
    END IF;
END;
$preflight_v3$;

-- 1. Add public_id column (nullable initially to allow safe backfill if rows exist)
ALTER TABLE public.reports ADD COLUMN public_id varchar(30);

-- 2. Backfill existing rows (if any exist) with standard Crockford Base32 ULIDs
-- ULID: 10 chars (48-bit timestamp from created_at) + 16 chars (80-bit randomness)
DO $backfill_ulid$
DECLARE
    crockford CONSTANT text := '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
    rec RECORD;
    epoch_ms bigint;
    ts_part text;
    rand_part text;
    generated_ulid text;
    i int;
    b int;
BEGIN
    FOR rec IN SELECT id, created_at FROM public.reports WHERE public_id IS NULL ORDER BY id FOR UPDATE LOOP
        epoch_ms := (EXTRACT(EPOCH FROM COALESCE(rec.created_at, clock_timestamp())) * 1000)::bigint;
        ts_part := '';
        FOR i IN REVERSE 9..0 LOOP
            b := ((epoch_ms >> (i * 5)) & 31)::integer;
            ts_part := ts_part || substr(crockford, b + 1, 1);
        END LOOP;

        rand_part := '';
        FOR i IN 1..16 LOOP
            b := floor(random() * 32)::integer;
            rand_part := rand_part || substr(crockford, b + 1, 1);
        END LOOP;

        generated_ulid := 'rpt_' || ts_part || rand_part;

        UPDATE public.reports SET public_id = generated_ulid WHERE id = rec.id;
    END LOOP;
END;
$backfill_ulid$;

-- 3. Enforce NOT NULL
ALTER TABLE public.reports ALTER COLUMN public_id SET NOT NULL;

-- 4. Enforce format constraint: rpt_ + 26-char Crockford Base32 ULID
-- Starts with 'rpt_', followed by Crockford Base32 char in [0-7] (128-bit ULID bound),
-- followed by 25 Crockford Base32 chars [0-9A-HJKMNP-TV-Z] (excludes I, L, O, U)
ALTER TABLE public.reports ADD CONSTRAINT reports_public_id_format_check
    CHECK (public_id ~ '^rpt_[0-7][0-9A-HJKMNP-TV-Z]{25}$');

-- 5. Enforce UNIQUE constraint
ALTER TABLE public.reports ADD CONSTRAINT reports_public_id_uq UNIQUE (public_id);

-- 6. Add documentation comment
COMMENT ON COLUMN public.reports.public_id IS
    'Public report identifier: rpt_ prefix + 26-character canonical Crockford Base32 ULID. Generated by Backend on creation, validated and indexed uniquely.';

COMMIT;
